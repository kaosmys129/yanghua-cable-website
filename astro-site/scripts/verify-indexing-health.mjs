import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const distDir = path.resolve(__dirname, '../dist/client');

console.log(`Starting SEO & Indexing audit on: ${distDir}`);

if (!fs.existsSync(distDir)) {
  console.error(`Dist directory does not exist! Please run build first.`);
  process.exit(1);
}

function getAllHtmlFiles(dir, fileList = []) {
  const files = fs.readdirSync(dir);
  for (const file of files) {
    const filePath = path.join(dir, file);
    const stat = fs.statSync(filePath);
    if (stat.isDirectory()) {
      getAllHtmlFiles(filePath, fileList);
    } else if (file.endsWith('.html')) {
      fileList.push(filePath);
    }
  }
  return fileList;
}

const htmlFiles = getAllHtmlFiles(distDir);
console.log(`Found ${htmlFiles.length} HTML files.`);

let errors = [];
let warnings = [];

// 1. Read sitemap-index.xml and referenced sitemaps
const sitemapIndexPath = path.join(distDir, 'sitemap-index.xml');
let sitemapUrls = new Set();

if (fs.existsSync(sitemapIndexPath)) {
  const sitemapIndexContent = fs.readFileSync(sitemapIndexPath, 'utf-8');
  const locMatches = [...sitemapIndexContent.matchAll(/<loc>(.*?)<\/loc>/g)].map(m => m[1]);
  console.log(`Found ${locMatches.length} sitemaps in sitemap-index.xml:`, locMatches);

  for (const subSitemapUrl of locMatches) {
    const fileName = path.basename(new URL(subSitemapUrl).pathname);
    const subSitemapPath = path.join(distDir, fileName);
    if (fs.existsSync(subSitemapPath)) {
      const content = fs.readFileSync(subSitemapPath, 'utf-8');
      const pageLocs = [...content.matchAll(/<loc>(.*?)<\/loc>/g)].map(m => m[1]);
      for (const loc of pageLocs) {
        sitemapUrls.add(loc);
      }
    } else {
      errors.push(`[Sitemap] Referenced sitemap file missing on disk: ${subSitemapPath}`);
    }
  }
} else {
  warnings.push(`[Sitemap] sitemap-index.xml missing in output!`);
}

console.log(`Total URLs registered in sitemap: ${sitemapUrls.size}`);

// Check each HTML file
for (const filePath of htmlFiles) {
  const relativePath = path.relative(distDir, filePath);
  const content = fs.readFileSync(filePath, 'utf-8');

  // Check if it is a redirect page generated by Astro
  const isRedirectPage = content.includes('http-equiv="refresh"') || content.includes('meta http-equiv="refresh"');

  // URL route for this HTML
  let routePath = '/' + relativePath.replace(/\/index\.html$/, '').replace(/\.html$/, '');
  if (routePath === '/index') routePath = '/';

  const fullUrl = `https://www.yhflexiblebusbar.com${routePath}`;

  // Check 1: Redirect page inside sitemap
  if (isRedirectPage) {
    if (sitemapUrls.has(fullUrl)) {
      errors.push(`[Sitemap Error] Redirect page '${fullUrl}' is included in sitemap! GSC will report 'Page with redirect'.`);
    }
    continue; // Skip further SEO meta checks for pure 301 redirect placeholder HTML files
  }

  // Check 2: Robots meta noindex
  const robotsMatch = content.match(/<meta\s+name="robots"\s+content="([^"]*)"/i);
  if (robotsMatch) {
    const robotsVal = robotsMatch[1].toLowerCase();
    if (robotsVal.includes('noindex')) {
      warnings.push(`[Noindex] '${routePath}' has robots='${robotsVal}'. Verify if this is intentional.`);
    }
  }

  // Check 3: Canonical tag
  if (routePath !== '/404') {
    const canonicalMatch = content.match(/<link\s+rel="canonical"\s+href="([^"]*)"/i);
    if (!canonicalMatch) {
      errors.push(`[Canonical Error] Missing <link rel="canonical"> in '${routePath}'`);
    } else {
      const canonicalHref = canonicalMatch[1];
      if (canonicalHref.endsWith('/') && canonicalHref !== 'https://www.yhflexiblebusbar.com/') {
        errors.push(`[Canonical Error] Canonical URL '${canonicalHref}' in '${routePath}' has trailing slash! (trailingSlash is 'never')`);
      }
    }
  }

  // Check 4: Hreflang alternates
  const hreflangMatches = [...content.matchAll(/<link\s+rel="alternate"\s+hreflang="([^"]*)"\s+href="([^"]*)"/gi)];
  for (const m of hreflangMatches) {
    const lang = m[1];
    const href = m[2];

    try {
      const urlObj = new URL(href);
      let targetPath = urlObj.pathname;
      if (targetPath.endsWith('/') && targetPath !== '/') {
        targetPath = targetPath.slice(0, -1);
      }
      
      let expectedHtmlPath = targetPath === '/' ? 'index.html' : path.join(targetPath.slice(1), 'index.html');
      let diskPath = path.join(distDir, expectedHtmlPath);
      
      if (!fs.existsSync(diskPath)) {
        errors.push(`[Hreflang Error] '${routePath}' has hreflang (${lang}) pointing to missing page '${href}' (Disk: ${expectedHtmlPath})`);
      } else {
        const targetContent = fs.readFileSync(diskPath, 'utf-8');
        if (targetContent.includes('http-equiv="refresh"')) {
          errors.push(`[Hreflang Error] '${routePath}' has hreflang (${lang}) pointing to 301 Redirect page '${href}'`);
        }
      }
    } catch (e) {
      errors.push(`[Hreflang Error] Invalid href '${href}' in '${routePath}'`);
    }
  }

  // Check 5: Internal links <a href="...">
  const aMatches = [...content.matchAll(/<a\s+[^>]*href="([^"]*)"/gi)];
  for (const m of aMatches) {
    const href = m[1];
    if (href.startsWith('/') && !href.startsWith('//')) {
      // Internal link
      let linkPath = href.split('?')[0].split('#')[0];
      if (linkPath.endsWith('/') && linkPath !== '/') {
        linkPath = linkPath.slice(0, -1);
      }
      const targetHtmlPath = linkPath === '/' ? 'index.html' : path.join(linkPath.slice(1), 'index.html');
      const targetDiskPath = path.join(distDir, targetHtmlPath);
      
      if (!fs.existsSync(targetDiskPath)) {
        errors.push(`[Internal Link Error] '${routePath}' links to missing page (404): '${href}'`);
      } else {
        const targetContent = fs.readFileSync(targetDiskPath, 'utf-8');
        if (targetContent.includes('http-equiv="refresh"')) {
          warnings.push(`[Internal Link Warning] '${routePath}' links to 301 Redirect page: '${href}'`);
        }
      }
    }
  }
}

// Check sitemap URLs to ensure all sitemap URLs correspond to valid non-redirect HTML
for (const sUrl of sitemapUrls) {
  try {
    const u = new URL(sUrl);
    let p = u.pathname;
    if (p.endsWith('/') && p !== '/') p = p.slice(0, -1);
    const htmlFile = p === '/' ? 'index.html' : path.join(p.slice(1), 'index.html');
    const diskPath = path.join(distDir, htmlFile);

    if (!fs.existsSync(diskPath)) {
      errors.push(`[Sitemap Error] Sitemap URL '${sUrl}' does not exist on disk (${htmlFile})! GSC 404.`);
    } else {
      const c = fs.readFileSync(diskPath, 'utf-8');
      if (c.includes('http-equiv="refresh"')) {
        errors.push(`[Sitemap Error] Sitemap URL '${sUrl}' is a 301 Redirect page! GSC 'Page with redirect'.`);
      }
    }
  } catch (e) {
    errors.push(`[Sitemap Error] Invalid sitemap URL '${sUrl}'`);
  }
}

console.log('\n================ AUDIT REPORT ================');
console.log(`TOTAL ERRORS: ${errors.length}`);
console.log(`TOTAL WARNINGS: ${warnings.length}`);

if (errors.length > 0) {
  console.log('\n--- ERRORS ---');
  errors.slice(0, 30).forEach(e => console.log('❌', e));
  if (errors.length > 30) console.log(`... and ${errors.length - 30} more errors.`);
}

if (warnings.length > 0) {
  console.log('\n--- WARNINGS ---');
  warnings.slice(0, 20).forEach(w => console.log('⚠️', w));
  if (warnings.length > 20) console.log(`... and ${warnings.length - 20} more warnings.`);
}

console.log('===============================================\n');
process.exit(errors.length > 0 ? 1 : 0);
